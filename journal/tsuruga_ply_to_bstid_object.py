AXES = ("x", "y", "f", "t")
WEB_MERCATOR_LAT_MAX = 85.0511287798066

# Manuscript altitude quantization range.
H_MIN = -16383.0
H_MAX = 16384.0
H_SPAN = H_MAX - H_MIN


# ---------------------------------------------------------------------------
# Utility functions
# ---------------------------------------------------------------------------

def load_anchor_metadata(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))

    geo = data.get("geographic_anchor", {})
    lat = geo.get("latitude_deg")
    lon = geo.get("longitude_deg")
    alt = geo.get("absolute_altitude_m")

    if lat is None or lon is None:
        raise RuntimeError(
            "Transform JSON does not contain geographic_anchor latitude/longitude."
        )

    return {
        "lat": float(lat),
        "lon": float(lon),
        "alt": None if alt is None else float(alt),
        "raw": data,
    }


def parse_crop(crop_values):
    if crop_values is None:
        return None
    if len(crop_values) != 6:
        raise ValueError("--crop requires 6 values: xmin xmax ymin ymax zmin zmax")
    return tuple(float(v) for v in crop_values)


def crop_points(points: np.ndarray, crop):
    if crop is None:
        return points

    xmin, xmax, ymin, ymax, zmin, zmax = crop
    keep = (
        (points[:, 0] >= xmin) & (points[:, 0] <= xmax) &
        (points[:, 1] >= ymin) & (points[:, 1] <= ymax) &
        (points[:, 2] >= zmin) & (points[:, 2] <= zmax)
    )
    return points[keep]


def voxelize_surface(
    points: np.ndarray,
    voxel_size: float,
    margin_voxels: int,
):
    """
    Quantize point samples onto a dense local voxel grid.

    Returns:
        shell, origin
    where origin is the metric coordinate of voxel index (0,0,0)'s lower corner.
    """
    pmin = points.min(axis=0)
    pmax = points.max(axis=0)

    origin = np.floor(pmin / voxel_size) * voxel_size
    origin -= margin_voxels * voxel_size

    upper = np.ceil(pmax / voxel_size) * voxel_size
    upper += margin_voxels * voxel_size

    shape = np.ceil((upper - origin) / voxel_size).astype(int) + 1
    shape = tuple(int(v) for v in shape)

    ijk = np.floor((points - origin) / voxel_size).astype(np.int64)
    ijk = np.clip(ijk, [0, 0, 0], np.array(shape) - 1)

    shell = np.zeros(shape, dtype=bool)
    shell[ijk[:, 0], ijk[:, 1], ijk[:, 2]] = True

    return shell, origin


def close_shell(shell: np.ndarray, iterations: int) -> np.ndarray:
    if iterations <= 0:
        return shell

    # 26-neighbour 3x3x3 structure.  This is only used to bridge small
    # sampling gaps in the sampled surface.
    structure = np.ones((3, 3, 3), dtype=bool)
    return ndimage.binary_closing(
        shell,
        structure=structure,
        iterations=iterations,
    )


def directional_fill(shell: np.ndarray, require_ns: bool = False):
    """
    User-proposed interior rule:

      an empty voxel is filled if a shell voxel exists:
        * somewhere to the WEST on the same (y,z) scanline,
        * somewhere to the EAST on the same (y,z) scanline,
        * somewhere ABOVE on the same (x,y) vertical column.

    Optionally require north/south enclosure too.

    X = East, Y = North, Z = Up.
    """

    # WEST: any occupied voxel at smaller x.
    west = np.zeros_like(shell)
    cum = np.maximum.accumulate(shell, axis=0)
    west[1:, :, :] = cum[:-1, :, :]

    # EAST: any occupied voxel at larger x.
    east = np.zeros_like(shell)
    cum = np.maximum.accumulate(shell[::-1, :, :], axis=0)[::-1, :, :]
    east[:-1, :, :] = cum[1:, :, :]

    # UP: any occupied voxel at larger z.
    up = np.zeros_like(shell)
    cum = np.maximum.accumulate(shell[:, :, ::-1], axis=2)[:, :, ::-1]
    up[:, :, :-1] = cum[:, :, 1:]

    interior = (~shell) & west & east & up

    if require_ns:
        south = np.zeros_like(shell)
        cum = np.maximum.accumulate(shell, axis=1)
        south[:, 1:, :] = cum[:, :-1, :]

        north = np.zeros_like(shell)
        cum = np.maximum.accumulate(shell[:, ::-1, :], axis=1)[:, ::-1, :]
        north[:, :-1, :] = cum[:, 1:, :]

        interior &= south & north

    solid = shell | interior
    return solid, interior


def flood_fill(shell: np.ndarray):
    """
    Fill all empty voxels not reachable from the padded exterior.

    Equivalent conceptually to a 3-D exterior flood fill.
    """
    structure = ndimage.generate_binary_structure(rank=3, connectivity=1)
    solid = ndimage.binary_fill_holes(shell, structure=structure)
    interior = solid & (~shell)
    return solid, interior


def voxel_centers(mask: np.ndarray, origin: np.ndarray, voxel_size: float):
    ijk = np.argwhere(mask)
    centers = origin + (ijk.astype(np.float64) + 0.5) * voxel_size
    return ijk, centers


def save_centers_ply(path: Path, centers: np.ndarray):
    pcd = o3d.geometry.PointCloud()
    pcd.points = o3d.utility.Vector3dVector(centers)
    if not o3d.io.write_point_cloud(str(path), pcd, write_ascii=False):
        raise RuntimeError(f"Could not write {path}")


def make_local_to_wgs84(anchor_lat: float, anchor_lon: float):
    """
    Use a local azimuthal-equidistant CRS centered on the selected anchor.
    For the ~100-150 m castle extent this gives a convenient ENU-like
    East/North metric mapping.
    """
    local_crs = CRS.from_proj4(
        f"+proj=aeqd +lat_0={anchor_lat:.12f} "
        f"+lon_0={anchor_lon:.12f} +datum=WGS84 +units=m +no_defs"
    )
    wgs84 = CRS.from_epsg(4326)
    return Transformer.from_crs(local_crs, wgs84, always_xy=True)


def lonlat_to_webmercator_prefix(
    lon_deg: np.ndarray,
    lat_deg: np.ndarray,
    z: int,
):
    """
    Slippy/Web-Mercator hierarchical integer cell index at zoom z.
    """
    n = float(1 << z)

    lon = ((lon_deg + 180.0) % 360.0) - 180.0
    lat = np.clip(lat_deg, -WEB_MERCATOR_LAT_MAX, WEB_MERCATOR_LAT_MAX)

    x_norm = (lon + 180.0) / 360.0

    lat_rad = np.radians(lat)
    y_norm = (
        1.0
        - np.arcsinh(np.tan(lat_rad)) / math.pi
    ) / 2.0

    ix = np.floor(x_norm * n).astype(np.int64)
    iy = np.floor(y_norm * n).astype(np.int64)

    max_i = (1 << z) - 1
    ix = np.clip(ix, 0, max_i)
    iy = np.clip(iy, 0, max_i)

    return ix, iy


def altitude_to_prefix(h_m: np.ndarray, z: int):
    """
    BST-ID manuscript altitude quantization:
        [-16383, 16384] m
    """
    n = float(1 << z)
    u = (h_m - H_MIN) / H_SPAN
    # Keep endpoint exactly inside the finite index domain.
    u = np.clip(u, 0.0, np.nextafter(1.0, 0.0))
    ih = np.floor(u * n).astype(np.int64)
    return ih


def unique_bstid_triplets(
    centers_enu: np.ndarray,
    anchor_lat: float,
    anchor_lon: float,
    anchor_alt: float,
    zx: int,
    zy: int,
    zh: int,
):
    transformer = make_local_to_wgs84(anchor_lat, anchor_lon)

    east = centers_enu[:, 0]
    north = centers_enu[:, 1]
    up = centers_enu[:, 2]

    lon, lat = transformer.transform(east, north)
    lon = np.asarray(lon, dtype=np.float64)
    lat = np.asarray(lat, dtype=np.float64)

    h = anchor_alt + up

    ix, iy = lonlat_to_webmercator_prefix(lon, lat, zx)
    # Compute y independently if zx != zy.
    if zy != zx:
        _, iy = lonlat_to_webmercator_prefix(lon, lat, zy)

    ih = altitude_to_prefix(h, zh)

    triplets = np.column_stack((ix, iy, ih))
    triplets = np.unique(triplets, axis=0)

    return triplets


def triplets_to_cells(triplets: np.ndarray, zx: int, zy: int, zh: int):
    cells = []
    append = cells.append
    for ix, iy, ih in triplets:
        append(
            Cell.from_parts(
                x=(zx, int(ix)),
                y=(zy, int(iy)),
                f=(zh, int(ih)),
            )
        )
    return cells


def normalize_cells(cells, mode: str):
    if mode == "indexed-batch":
        if not HAVE_INDEXED_BATCH:
            raise RuntimeError(
                "normalize_indexed_batch() was not found in bst_id.region_index.\n"
                "Add the indexed normalization implementation or use "
                "--normalizer reference for a small test case."
            )
        return normalize_indexed_batch(cells)

    if mode == "reference":
        if len(cells) > 10_000:
            print(
                "WARNING: reference normalize() has a conservative high-order "
                "cost and may be very slow for this many cells.",
                file=sys.stderr,
            )
        return normalize(cells)

    raise ValueError(mode)


def extract_cell_row(cell):
    """
    Current reference Cell stores zooms/values in x,y,f,t order.
    Export f as h in the CSV.
    """
    zooms = tuple(cell.zooms)
    values = tuple(cell.values)

    return {
        "zx": zooms[0],
        "ix": values[0],
        "zy": zooms[1],
        "iy": values[1],
        "zh": zooms[2],
        "ih": values[2],
    }


def zoom_vector_statistics(cells):
    counter = Counter()
    axis_merged = Counter()

    for c in cells:
        row = extract_cell_row(c)
        zv = (row["zx"], row["zy"], row["zh"])
        counter[zv] += 1

    return counter


def save_prefix_csv(path: Path, cells):
    with path.open("w", newline="", encoding="utf-8") as f:
        fieldnames = ["zx", "ix", "zy", "iy", "zh", "ih"]
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for cell in cells:
            w.writerow(extract_cell_row(cell))


def verify_normalized_semantics(fine_cells, normalized_cells, zx, zy, zh):
    working_zoom = {"x": zx, "y": zy, "f": zh}
    a = region_atoms(fine_cells, working_zoom)
    b = region_atoms(normalized_cells, working_zoom)
    return a == b, len(a), len(b)


