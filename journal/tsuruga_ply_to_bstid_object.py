#!/usr/bin/env python3
"""
tsuruga_ply_to_bstid_object.py

Convert the aligned Tsuruga Castle point cloud into a filled 3-D occupancy
object and then into a normalized BST-ID XYH region.

Pipeline
--------
aligned PLY
  -> surface voxelization on a local metric grid
  -> small-gap closing (optional)
  -> interior filling
       * directional: WEST + EAST + UP enclosure rule
       * flood:       exterior flood-fill / enclosed-volume rule
  -> solid local voxels
  -> local ENU-like coordinates -> WGS84 lon/lat
  -> fine BST-ID XYH cells
  -> BST-ID normalization
  -> CSV / JSON / PLY outputs

The current Tsuruga alignment metadata is read from the JSON generated by
tsuruga_obj_anchor.py.

Recommended first run
---------------------
python tsuruga_ply_to_bstid_object.py ^
    tsuruga_aligned.ply ^
    --transform-json tsuruga_enu_anchor_transform.json ^
    --voxel-size 1.0 ^
    --fill-mode directional ^
    --close-iterations 1 ^
    --zx 25 --zy 25 --zh 15

Notes
-----
* BST-ID uses axis name "f" internally for height in the current reference
  implementation, while this script reports it as h in CSV/JSON.
* If the transform JSON contains no absolute anchor altitude, local U is used
  as height with anchor altitude 0 m unless --anchor-alt is supplied.
* Default normalization is "indexed-batch", because the transparent reference
  normalize() can be prohibitively slow on large solid objects.
"""

